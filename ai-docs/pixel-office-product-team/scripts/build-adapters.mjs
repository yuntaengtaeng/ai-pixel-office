import {
  cpSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

/**
 * 공통 Agent 진입 지침과 Skill 원본을 Codex 및 Claude가 발견할 수 있는 배포 레이아웃으로 생성
 *
 * 원본의 카테고리 디렉터리는 탐색기가 읽지 못하므로 runtime Skill 루트 바로 아래로 평탄화
 * 현재 프로젝트에 설치하거나 기존 AGENTS.md 및 CLAUDE.md를 변경하지 않고 adapters 내부만 교체
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skills = join(root, "skills");

/** 중첩된 원본 카테고리에서 실제 SKILL.md를 소유한 디렉터리 탐색 */
function skillDirectories(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    if (!statSync(path).isDirectory()) return [];
    if (readdirSync(path).includes("SKILL.md")) return [path];
    return skillDirectories(path);
  });
}

const sourceSkills = skillDirectories(skills);
const skillNames = sourceSkills.map((path) => path.split(/[\\/]/).at(-1));

// 배포 단계에서 카테고리를 제거하므로 같은 폴더 이름이 덮어써지는 상황을 생성 전에 차단
if (new Set(skillNames).size !== skillNames.length) {
  throw new Error("Skill folder names must be unique across categories");
}

const targets = [
  {
    runtime: "codex",
    entry: "AGENTS.md",
    skillRoot: join(".agents", "skills"),
  },
  {
    runtime: "claude",
    entry: "CLAUDE.md",
    skillRoot: join(".claude", "skills"),
  },
];

for (const target of targets) {
  const output = join(root, "adapters", target.runtime, "generated");
  rmSync(output, { recursive: true, force: true });
  mkdirSync(output, { recursive: true });
  const header = "<!-- Generated by scripts/build-adapters.mjs. Do not edit. -->\n\n";
  writeFileSync(
    join(output, target.entry),
    header + readFileSync(join(root, target.entry), "utf8"),
    "utf8",
  );
  const outputSkills = join(output, target.skillRoot);
  mkdirSync(outputSkills, { recursive: true });
  for (const sourceSkill of sourceSkills) {
    cpSync(sourceSkill, join(outputSkills, sourceSkill.split(/[\\/]/).at(-1)), { recursive: true });
  }
}

process.stdout.write("Generated Codex and Claude adapters\n");
